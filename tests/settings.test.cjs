const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
let saved = { enabled: true, mode: 'mirror', layers: 12, displayDistance: 150, band: 0.32, blur: 40, inertia: 200, dimming: 25, shadow: 10 };
const sandbox = { localStorage: { getItem: () => JSON.stringify(saved) } };
const source = fs.readFileSync('src/ui/panel.js', 'utf8');
vm.runInNewContext(source, sandbox);
const proto = sandbox.BiliAmbient.SettingsPanel.prototype;
const loaded = () => proto.load.call({ clamp: proto.clamp });
assert.equal(loaded().layers, 12); assert.equal(loaded().displayDistance, 150); assert.equal(loaded().inertia, 200);
assert.equal(loaded().dimming, 25); assert.equal(loaded().shadow, 10);
saved = { layers: 99, displayDistance: 9999, band: 99, inertia: 9999, dimming: 999, shadow: 999 };
assert.equal(loaded().layers, 12); assert.equal(loaded().displayDistance, 500); assert.equal(loaded().band, 1.0); assert.equal(loaded().inertia, 400);
assert.equal(loaded().dimming, 100); assert.equal(loaded().shadow, 100);
saved = {};
assert.equal(loaded().mode, 'forward', 'Default mode is forward');
assert.equal(loaded().blur, 18, 'Default blur is 18');
assert.equal(loaded().band, 1.00, 'Default band is 100%');
assert.equal(loaded().layers, 12, 'Default layers is 12');
assert.equal(loaded().displayDistance, 200, 'Old saved preferences acquire the new default');
assert.equal(loaded().inertia, 120, 'Old saved preferences acquire the default inertia');
assert.equal(loaded().dimming, 0, 'Default dimming is 0');
assert.equal(loaded().shadow, 50, 'Default shadow is 50');
assert.equal(loaded().resolution, 1.0, 'Resolution is locked to 1.0');
assert(source.includes('max="12"'));
assert(source.includes('max="500"'));
assert(source.includes('max="1.00"'));
assert(source.includes('data-setting="displayDistance"'));
assert(source.includes('data-setting="inertia"'));
assert(source.includes('data-setting="dimming"'));
assert(source.includes('data-setting="shadow"'));
assert(!source.includes('data-setting="shadowSpread"'), 'Shadow spread control must be removed');
assert(!source.includes('data-setting="shadowColor"'), 'Shadow color control must be removed');
assert(!source.includes('data-setting="resolution"'), 'Resolution UI control must be removed');
assert(!source.includes('控制下方氛围灯延伸距离'), 'Hint text must be removed');
assert(!source.includes('edgeShadow') && !source.includes('rightFade'));

const { computeDropShadow } = sandbox.BiliAmbient;
assert.equal(computeDropShadow(0), 'none');
const shadowStr = computeDropShadow(20);
assert(shadowStr.includes('rgba(0, 0, 0, 0.12)'));
assert(shadowStr.includes('rgba(0, 0, 0, 0.015)'));
assert.equal((shadowStr.match(/rgba/g) || []).length, 6, 'Must generate 6-layer progressive diffusion drop shadow');

console.log('PASS: 12-layer settings, adjustable display distance and inertia, dimming and progressive drop-shadow, old preferences migration, removed controls and hints');
